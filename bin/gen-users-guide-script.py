#!/usr/bin/env python3
"""Generate users-guide-script.txt from the users guide.

doc/usr/users-guide.md is the source of truth.  Its runnable urQL code
blocks become dojo `=uql` lines, in order, under the guide's headings, from
"Database Schema" up to "Scries and Subscriptions", plus Appendix I.  Dojo
command lines in the guide (`:obelisk ...`, `(parse:parse ...)`) are copied
as written.  Result output, error messages, `<placeholder>` templates, and
Hoon are skipped.

Run from anywhere:  python3 bin/gen-users-guide-script.py
"""
import re
from pathlib import Path

DOC = Path(__file__).resolve().parent.parent / 'desk' / 'doc'
GUIDE = DOC / 'usr' / 'users-guide.md'
SCRIPT = DOC / 'dev' / 'users-guide-script.txt'

URQL = re.compile(r'^(FROM|SELECT|CREATE|INSERT|WITH|UPDATE|DELETE|UPSERT|'
                  r'ALTER|DROP|TRUNCATE|GRANT|REVOKE)\b(?!:)')
PLACEHOLDER = re.compile(r'<[a-z-]+>')
HEADER = [
    '::  urQL examples of doc/usr/users-guide.md, in order, for the dojo.',
    '::  Generated by bin/gen-users-guide-script.py from the users guide,',
    '::  which is the source of truth.  Set uql with each =uql line, then',
    '::  poke it into a database:',
    '',
    ':obelisk &obelisk-action [%script %db1 %vector uql]',
]
SAMPLE_DB_POKE = ':obelisk &obelisk-action [%script %animal-shelter %vector uql]'


def items(lines):
    """Headings as ('h', level, text) and code blocks as ('b', lines)."""
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith('```'):
            j = i + 1
            block = []
            while not lines[j].startswith('```'):
                block.append(lines[j])
                j += 1
            yield ('b', block)
            i = j + 1
            continue
        m = re.match(r'^(#+) (.*)', line)
        if m:
            yield ('h', len(m.group(1)), m.group(2))
        i += 1


def tape(text):
    """Escape text for a Hoon tape: backslash, double quote, and {."""
    return text.replace('\\', '\\\\').replace('"', '\\"').replace('{', '\\{')


def uql_lines(block):
    """A urQL block as a =uql tape, one piece per line.  A block with
    comments joins its lines with newlines, so a :: comment ends at its
    line and /* */ stay in columns 1 and 2."""
    comments = any('::' in x or '/*' in x or '*/' in x for x in block)
    sep = '\\0a' if comments else ' '
    pieces = [tape(x.rstrip()) for x in block]
    out = []
    for k, piece in enumerate(pieces):
        prefix = '=uql ' if k == 0 else ''
        if k < len(pieces) - 1:
            out.append(f'{prefix}"{piece}{sep}".')
        else:
            out.append(f'{prefix}"{piece}"')
    return out


def generate():
    out = []
    pending = []          # headings not yet emitted, outermost first
    started = False
    for item in items(GUIDE.read_text().split('\n')):
        if item[0] == 'h':
            level, text = item[1], item[2]
            if text == 'Database Schema' or text.startswith('APPENDIX I:'):
                started = True
            if text.startswith('Scries and Subscriptions'):
                started = False
            if text.startswith('APPENDIX II'):
                break
            if started:
                pending = [p for p in pending if p[0] < level] + [(level, text)]
            continue
        if not started:
            continue
        block = [x for x in item[1] if x.strip()]
        if not block:
            continue
        first = block[0].strip()
        urql = bool(URQL.match(first)) and \
            not any(PLACEHOLDER.search(x) for x in block)
        command = first.startswith(':obelisk') or first.startswith('(parse:parse')
        if not (urql or command):
            continue
        for level, text in pending:
            out += ['', '#' * level + ' ' + text]
        pending = []
        out.append('')
        if command:
            out += block
            if 'all-animal-shelter' in first:
                out += ['', SAMPLE_DB_POKE]
        else:
            out += uql_lines(block)
    SCRIPT.write_text('\n'.join(HEADER + out) + '\n')


if __name__ == '__main__':
    generate()
